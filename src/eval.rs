use std::collections::HashSet;

use crate::ast::*;

pub fn compile_to_js(program: &Program) -> String {
    let family_names: HashSet<String> = program
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Family(f) => Some(f.name.clone()),
            _ => None,
        })
        .collect();

    let mut emitter = Emitter::new(family_names);
    emitter.emit_program(program)
}

struct Emitter {
    family_names: HashSet<String>,
    scopes: Vec<HashSet<String>>,
    loop_id: usize,
}

impl Emitter {
    fn new(family_names: HashSet<String>) -> Self {
        Self {
            family_names,
            scopes: vec![HashSet::new()],
            loop_id: 0,
        }
    }

    fn emit_program(&mut self, program: &Program) -> String {
        // Function declarations are visible throughout the module, including
        // calls emitted before the declaration itself.
        for item in &program.items {
            if let Item::Func(function) = item {
                self.declare(&function.name);
            }
        }
        let mut out = String::new();
        out.push_str(&format!("// Generated by marslang {}\n", crate::VERSION));
        out.push_str(include_str!("runtime.js.inc"));
        out.push('\n');

        for item in &program.items {
            self.emit_item(item, 0, &mut out);
        }

        if program
            .items
            .iter()
            .any(|i| matches!(i, Item::Func(f) if f.name == "m"))
        {
            out.push_str("\nm();\n");
        }

        out
    }

    fn emit_item(&mut self, item: &Item, indent: usize, out: &mut String) {
        match item {
            Item::Import(i) => {
                if let Some(alias) = &i.alias {
                    line(
                        indent,
                        &format!("const {} = require('./{}');", alias, i.module),
                        out,
                    );
                } else {
                    line(indent, &format!("require('./{}');", i.module), out);
                }
            }
            Item::Var(v) => {
                self.declare(&v.name);
                self.emit_var(v, indent, out)
            }
            Item::Func(f) => self.emit_func(f, indent, out),
            Item::Family(c) => self.emit_family(c, indent, out),
            Item::Stmt(s) => self.emit_stmt(s, indent, out),
        }
    }

    fn emit_var(&mut self, v: &VarDecl, indent: usize, out: &mut String) {
        let kw = if v.is_fixed || v.temp == TempKind::Hot {
            "const"
        } else {
            "let"
        };
        line(
            indent,
            &format!("{} {} = {};", kw, v.name, self.emit_expr(&v.value)),
            out,
        );
    }

    fn emit_func(&mut self, f: &FuncDecl, indent: usize, out: &mut String) {
        let args = f
            .params
            .iter()
            .map(|p| p.name.clone())
            .collect::<Vec<_>>()
            .join(", ");
        match &f.body {
            FuncBody::Block(stmts) => {
                line(indent, &format!("function {}({}) {{", f.name, args), out);
                self.push_scope();
                for p in &f.params {
                    self.declare(&p.name);
                    line(indent + 1, &format!("{} = __mars.typed({}, {:?});", p.name, p.name, p.ty), out);
                }
                for s in stmts {
                    self.emit_stmt(s, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
            }
            FuncBody::Expr(e) => {
                self.push_scope();
                for p in &f.params {
                    self.declare(&p.name);
                }
                let expr = self.emit_expr(e);
                self.pop_scope();
                line(
                    indent,
                    &format!("function {}({}) {{ {} return {}; }}", f.name, args, parameter_checks(&f.params), expr),
                    out,
                );
            }
        }
    }

    fn emit_family(&mut self, c: &FamilyDecl, indent: usize, out: &mut String) {
        let ext = c
            .extends
            .as_ref()
            .map(|e| format!(" extends {}", e))
            .unwrap_or_default();
        line(indent, &format!("class {}{} {{", c.name, ext), out);
        for m in &c.methods {
            let args = m
                .params
                .iter()
                .map(|p| p.name.clone())
                .collect::<Vec<_>>()
                .join(", ");
            let name = if m.name == "init" {
                "constructor"
            } else {
                &m.name
            };
            match &m.body {
                FuncBody::Expr(e) => {
                    self.push_scope();
                    for p in &m.params {
                        self.declare(&p.name);
                    }
                    let expr = self.emit_expr(e);
                    self.pop_scope();
                    line(
                        indent + 1,
                        &format!("{}({}) {{ {} return {}; }}", name, args, parameter_checks(&m.params), expr),
                        out,
                    );
                }
                FuncBody::Block(stmts) => {
                    line(indent + 1, &format!("{}({}) {{", name, args), out);
                    self.push_scope();
                    for p in &m.params {
                        self.declare(&p.name);
                        line(indent + 2, &format!("{} = __mars.typed({}, {:?});", p.name, p.name, p.ty), out);
                    }
                    for s in stmts {
                        self.emit_stmt(s, indent + 2, out);
                    }
                    self.pop_scope();
                    line(indent + 1, "}", out);
                }
            }
        }
        line(indent, "}", out);
    }

    fn emit_stmt(&mut self, s: &Stmt, indent: usize, out: &mut String) {
        match s {
            Stmt::Var(v) => {
                self.declare(&v.name);
                self.emit_var(v, indent, out)
            }
            Stmt::Assign { target: Expr::Member { object, field }, value } => line(
                indent,
                &format!("__mars.setfield({}, {:?}, {});", self.emit_expr(object), field, self.emit_expr(value)),
                out,
            ),
            Stmt::Assign { target, value } => line(
                indent,
                &format!("{} = {};", self.emit_expr(target), self.emit_expr(value)),
                out,
            ),
            Stmt::Ret(e) => line(indent, &format!("return {};", self.emit_expr(e)), out),
            Stmt::Break => line(indent, "break;", out),
            Stmt::Continue => line(indent, "continue;", out),
            Stmt::While { cond, body } => {
                line(indent, &format!("while (__mars.truth({})) {{", self.emit_expr(cond)), out);
                self.push_scope();
                for stmt in body { self.emit_stmt(stmt, indent + 1, out); }
                self.pop_scope();
                line(indent, "}", out);
            }
            Stmt::ForEach { name, iterable, body } => {
                line(indent, &format!("for (let {} of __mars.iter({})) {{", name, self.emit_expr(iterable)), out);
                self.push_scope();
                self.declare(name);
                for stmt in body { self.emit_stmt(stmt, indent + 1, out); }
                self.pop_scope();
                line(indent, "}", out);
            }
            Stmt::For { init, cond, step, body } => {
                line(indent, "{", out); self.push_scope();
                for s in init { self.emit_stmt(s, indent + 1, out); }
                let mut updates = Vec::new();
                for s in step {
                    let mut text = String::new(); self.emit_stmt(s, 0, &mut text);
                    updates.push(text.trim().trim_end_matches(';').to_string());
                }
                line(indent + 1, &format!("for (; __mars.truth({}); {}) {{", self.emit_expr(cond), updates.join(", ")), out);
                self.push_scope(); for s in body { self.emit_stmt(s, indent + 2, out); } self.pop_scope();
                line(indent + 1, "}", out); self.pop_scope(); line(indent, "}", out);
            }
            Stmt::Expr(e) => line(indent, &format!("{};", self.emit_expr(e)), out),
            Stmt::Repeat { times, body } => {
                self.loop_id += 1;
                let id = self.loop_id;
                line(indent, "{", out);
                line(indent + 1, &format!("const __count{id} = __mars.repeat({});", self.emit_expr(times)), out);
                line(
                    indent + 1,
                    &format!(
                        "for (let __i{id} = 0; __i{id} < __count{id}; __i{id}++) {{"
                    ),
                    out,
                );
                self.push_scope();
                for st in body {
                    self.emit_stmt(st, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
                line(indent, "}", out);
            }
            Stmt::If {
                cond,
                then_block,
                elif_blocks,
                else_block,
            } => {
                line(indent, &format!("if (__mars.truth({})) {{", self.emit_expr(cond)), out);
                self.push_scope();
                for st in then_block {
                    self.emit_stmt(st, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
                for (ec, eb) in elif_blocks {
                    line(indent, &format!("else if (__mars.truth({})) {{", self.emit_expr(ec)), out);
                    self.push_scope();
                    for st in eb {
                        self.emit_stmt(st, indent + 1, out);
                    }
                    self.pop_scope();
                    line(indent, "}", out);
                }
                if let Some(eb) = else_block {
                    line(indent, "else {", out);
                    self.push_scope();
                    for st in eb {
                        self.emit_stmt(st, indent + 1, out);
                    }
                    self.pop_scope();
                    line(indent, "}", out);
                }
            }
        }
    }

    fn emit_expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Number(n) => {
                if n.chars().all(|c| c.is_ascii_digit()) && n.parse::<u64>().map(|v| v > 9_007_199_254_740_991).unwrap_or(true) {
                    format!("__mars.longint({n:?})")
                } else { n.clone() }
            }
            Expr::String(s) => s.clone(),
            Expr::Bool(b) => b.to_string(),
            Expr::Null => "null".into(),
            Expr::Ident(i) => {
                if i == "me" {
                    "this".into()
                } else {
                    i.clone()
                }
            }
            Expr::Raw(r) => r.clone(),
            Expr::Unary { op, value } => {
                if op == "-" {
                    if let Expr::Number(n) = value.as_ref() {
                        if n.chars().all(|c| c.is_ascii_digit()) && n.parse::<u64>().map(|v| v > 9_007_199_254_740_991).unwrap_or(true) {
                            return format!("__mars.longint(\"-{n}\")");
                        }
                    }
                }
                let value = self.emit_expr(value);
                if op == "not" { format!("(!__mars.truth({value}))") }
                else { format!("__mars.unary({op:?}, {value})") }
            }
            Expr::Member { object, field } => format!("{}.{}", self.emit_expr(object), field),
            Expr::Call { callee, args } => {
                let arg_text = args
                    .iter()
                    .map(|a| self.emit_expr(a))
                    .collect::<Vec<_>>()
                    .join(", ");

                if let Expr::Member { object, field } = callee.as_ref() {
                    if matches!(field.as_str(), "len" | "reverse" | "slice" | "lenslice") {
                        let method = if field == "len" { "length" } else { field.as_str() };
                        return format!("__mars.{method}({}{})", self.emit_expr(object),
                            if args.is_empty() { String::new() } else { format!(", {arg_text}") });
                    }
                    if field == "copy" && args.is_empty() {
                        return format!("__mars.copy({})", self.emit_expr(object));
                    }
                }

                if let Expr::Ident(name) = callee.as_ref() {
                    if self.is_unshadowed_builtin(name) {
                        return format!("__mars.{}({})", name, arg_text);
                    }
                    if self.is_unshadowed_family(name) {
                        return format!("new {}({})", name, arg_text);
                    }
                }

                format!("{}({})", self.emit_expr(callee), arg_text)
            }
            Expr::Binary { left, op, right } => {
                let left = self.emit_expr(left); let right = self.emit_expr(right);
                if op == "and" || op == "or" {
                    format!("(__mars.truth({left}) {} __mars.truth({right}))", if op == "and" { "&&" } else { "||" })
                } else { format!("__mars.bin({op:?}, {left}, {right})") }
            }
        }
    }

    fn is_unshadowed_builtin(&self, name: &str) -> bool {
        matches!(name, "out" | "slout" | "in" | "inln" | "a" | "s" | "p" | "arr" | "set" | "pair" | "map" | "dict" | "int" | "longint" | "float" | "string") && !self.is_shadowed(name)
    }

    fn is_unshadowed_family(&self, name: &str) -> bool {
        self.family_names.contains(name) && !self.is_shadowed(name)
    }

    fn is_shadowed(&self, name: &str) -> bool {
        self.scopes.iter().rev().any(|scope| scope.contains(name))
    }

    fn declare(&mut self, name: &str) {
        if let Some(scope) = self.scopes.last_mut() {
            scope.insert(name.to_string());
        }
    }

    fn push_scope(&mut self) {
        self.scopes.push(HashSet::new());
    }

    fn pop_scope(&mut self) {
        let _ = self.scopes.pop();
    }
}

fn parameter_checks(params: &[Param]) -> String {
    params.iter().map(|p| format!("{} = __mars.typed({}, {:?});", p.name, p.name, p.ty)).collect::<Vec<_>>().join(" ")
}

fn line(indent: usize, text: &str, out: &mut String) {
    out.push_str(&"    ".repeat(indent));
    out.push_str(text);
    out.push('\n');
}
