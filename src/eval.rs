use std::collections::HashSet;

use crate::ast::*;

pub fn compile_to_js(program: &Program) -> String {
    let family_names: HashSet<String> = program
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Family(f) => Some(f.name.clone()),
            _ => None,
        })
        .collect();

    let mut emitter = Emitter::new(family_names);
    emitter.emit_program(program)
}

struct Emitter {
    family_names: HashSet<String>,
    scopes: Vec<HashSet<String>>,
}

impl Emitter {
    fn new(family_names: HashSet<String>) -> Self {
        Self {
            family_names,
            scopes: vec![HashSet::new()],
        }
    }

    fn emit_program(&mut self, program: &Program) -> String {
        let mut out = String::new();
        out.push_str(&format!("// Generated by marslang {}\n", crate::VERSION));
        out.push_str("const __mars = {\n");
        out.push_str("  in: () => require('fs').readFileSync(0, 'utf8'),\n");
        out.push_str("  inln: (() => { let lines = null, i = 0; return () => { if (lines===null) lines = require('fs').readFileSync(0, 'utf8').split(/\\r?\\n/); return lines[i++] ?? ''; }; })(),\n");
        out.push_str("  out: (...xs) => console.log(...xs),\n");
        out.push_str("  slout: (...xs) => process.stdout.write(xs.map(String).join('')),\n");
        out.push_str("  a: (...xs) => xs,\n");
        out.push_str("  s: (...xs) => new Set(xs),\n");
        out.push_str("  p: (a,b) => ({ first: a, second: b }),\n");
        out.push_str("};\n\n");

        for item in &program.items {
            self.emit_item(item, 0, &mut out);
        }

        if program
            .items
            .iter()
            .any(|i| matches!(i, Item::Func(f) if f.name == "m"))
        {
            out.push_str("\nm();\n");
        }

        out
    }

    fn emit_item(&mut self, item: &Item, indent: usize, out: &mut String) {
        match item {
            Item::Import(i) => {
                if let Some(alias) = &i.alias {
                    line(
                        indent,
                        &format!("const {} = require('./{}');", alias, i.module),
                        out,
                    );
                } else {
                    line(indent, &format!("require('./{}');", i.module), out);
                }
            }
            Item::Var(v) => {
                self.declare(&v.name);
                self.emit_var(v, indent, out)
            }
            Item::Func(f) => self.emit_func(f, indent, out),
            Item::Family(c) => self.emit_family(c, indent, out),
            Item::Stmt(s) => self.emit_stmt(s, indent, out),
        }
    }

    fn emit_var(&mut self, v: &VarDecl, indent: usize, out: &mut String) {
        let kw = if v.is_fixed || v.temp == TempKind::Hot {
            "const"
        } else {
            "let"
        };
        line(
            indent,
            &format!("{} {} = {};", kw, v.name, self.emit_expr(&v.value)),
            out,
        );
    }

    fn emit_func(&mut self, f: &FuncDecl, indent: usize, out: &mut String) {
        let args = f
            .params
            .iter()
            .map(|p| p.name.clone())
            .collect::<Vec<_>>()
            .join(", ");
        match &f.body {
            FuncBody::Block(stmts) => {
                line(indent, &format!("function {}({}) {{", f.name, args), out);
                self.push_scope();
                for p in &f.params {
                    self.declare(&p.name);
                }
                for s in stmts {
                    self.emit_stmt(s, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
            }
            FuncBody::Expr(e) => {
                self.push_scope();
                for p in &f.params {
                    self.declare(&p.name);
                }
                let expr = self.emit_expr(e);
                self.pop_scope();
                line(
                    indent,
                    &format!("function {}({}) {{ return {}; }}", f.name, args, expr),
                    out,
                );
            }
        }
    }

    fn emit_family(&mut self, c: &FamilyDecl, indent: usize, out: &mut String) {
        let ext = c
            .extends
            .as_ref()
            .map(|e| format!(" extends {}", e))
            .unwrap_or_default();
        line(indent, &format!("class {}{} {{", c.name, ext), out);
        for m in &c.methods {
            let args = m
                .params
                .iter()
                .map(|p| p.name.clone())
                .collect::<Vec<_>>()
                .join(", ");
            let name = if m.name == "init" {
                "constructor"
            } else {
                &m.name
            };
            match &m.body {
                FuncBody::Expr(e) => {
                    self.push_scope();
                    for p in &m.params {
                        self.declare(&p.name);
                    }
                    let expr = self.emit_expr(e);
                    self.pop_scope();
                    line(
                        indent + 1,
                        &format!("{}({}) {{ return {}; }}", name, args, expr),
                        out,
                    );
                }
                FuncBody::Block(stmts) => {
                    line(indent + 1, &format!("{}({}) {{", name, args), out);
                    self.push_scope();
                    for p in &m.params {
                        self.declare(&p.name);
                    }
                    for s in stmts {
                        self.emit_stmt(s, indent + 2, out);
                    }
                    self.pop_scope();
                    line(indent + 1, "}", out);
                }
            }
        }
        line(indent, "}", out);
    }

    fn emit_stmt(&mut self, s: &Stmt, indent: usize, out: &mut String) {
        match s {
            Stmt::Var(v) => {
                self.declare(&v.name);
                self.emit_var(v, indent, out)
            }
            Stmt::Assign { target, value } => line(
                indent,
                &format!("{} = {};", self.emit_expr(target), self.emit_expr(value)),
                out,
            ),
            Stmt::Ret(e) => line(indent, &format!("return {};", self.emit_expr(e)), out),
            Stmt::Expr(e) => line(indent, &format!("{};", self.emit_expr(e)), out),
            Stmt::Repeat { times, body } => {
                line(
                    indent,
                    &format!(
                        "for (let __i = 0; __i < ({}); __i++) {{",
                        self.emit_expr(times)
                    ),
                    out,
                );
                self.push_scope();
                self.declare("__i");
                for st in body {
                    self.emit_stmt(st, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
            }
            Stmt::If {
                cond,
                then_block,
                elif_blocks,
                else_block,
            } => {
                line(indent, &format!("if ({}) {{", self.emit_expr(cond)), out);
                self.push_scope();
                for st in then_block {
                    self.emit_stmt(st, indent + 1, out);
                }
                self.pop_scope();
                line(indent, "}", out);
                for (ec, eb) in elif_blocks {
                    line(indent, &format!("else if ({}) {{", self.emit_expr(ec)), out);
                    self.push_scope();
                    for st in eb {
                        self.emit_stmt(st, indent + 1, out);
                    }
                    self.pop_scope();
                    line(indent, "}", out);
                }
                if let Some(eb) = else_block {
                    line(indent, "else {", out);
                    self.push_scope();
                    for st in eb {
                        self.emit_stmt(st, indent + 1, out);
                    }
                    self.pop_scope();
                    line(indent, "}", out);
                }
            }
        }
    }

    fn emit_expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Number(n) => n.clone(),
            Expr::String(s) => s.clone(),
            Expr::Bool(b) => b.to_string(),
            Expr::Null => "null".into(),
            Expr::Ident(i) => {
                if i == "me" {
                    "this".into()
                } else {
                    i.clone()
                }
            }
            Expr::Raw(r) => r.clone(),
            Expr::Member { object, field } => format!("{}.{}", self.emit_expr(object), field),
            Expr::Call { callee, args } => {
                let arg_text = args
                    .iter()
                    .map(|a| self.emit_expr(a))
                    .collect::<Vec<_>>()
                    .join(", ");

                if let Expr::Ident(name) = callee.as_ref() {
                    if self.is_unshadowed_builtin(name) {
                        return format!("__mars.{}({})", name, arg_text);
                    }
                    if self.is_unshadowed_family(name) {
                        return format!("new {}({})", name, arg_text);
                    }
                }

                format!("{}({})", self.emit_expr(callee), arg_text)
            }
            Expr::Binary { left, op, right } => {
                format!(
                    "({} {} {})",
                    self.emit_expr(left),
                    op,
                    self.emit_expr(right)
                )
            }
        }
    }

    fn is_unshadowed_builtin(&self, name: &str) -> bool {
        matches!(name, "out" | "slout" | "in" | "inln" | "a" | "s" | "p") && !self.is_shadowed(name)
    }

    fn is_unshadowed_family(&self, name: &str) -> bool {
        self.family_names.contains(name) && !self.is_shadowed(name)
    }

    fn is_shadowed(&self, name: &str) -> bool {
        self.scopes.iter().rev().any(|scope| scope.contains(name))
    }

    fn declare(&mut self, name: &str) {
        if let Some(scope) = self.scopes.last_mut() {
            scope.insert(name.to_string());
        }
    }

    fn push_scope(&mut self) {
        self.scopes.push(HashSet::new());
    }

    fn pop_scope(&mut self) {
        let _ = self.scopes.pop();
    }
}

fn line(indent: usize, text: &str, out: &mut String) {
    out.push_str(&"    ".repeat(indent));
    out.push_str(text);
    out.push('\n');
}
