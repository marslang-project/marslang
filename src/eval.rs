use crate::ast::*;

pub fn compile_to_js(program: &Program) -> String {
    let mut out = String::new();
    out.push_str("// Generated by marslang rs-0.1\n");
    out.push_str("const __mars = {\n");
    out.push_str("  in: () => require('fs').readFileSync(0, 'utf8'),\n");
    out.push_str("  inln: (() => { let lines = null, i = 0; return () => { if (lines===null) lines = require('fs').readFileSync(0, 'utf8').split(/\\r?\\n/); return lines[i++] ?? ''; }; })(),\n");
    out.push_str("  out: (...xs) => console.log(...xs),\n");
    out.push_str("  slout: (...xs) => process.stdout.write(xs.map(String).join('')),\n");
    out.push_str("  a: (...xs) => xs,\n");
    out.push_str("  s: (...xs) => new Set(xs),\n");
    out.push_str("  p: (a,b) => ({ first: a, second: b }),\n");
    out.push_str("};\n\n");

    for item in &program.items {
        emit_item(item, 0, &mut out);
    }

    if program
        .items
        .iter()
        .any(|i| matches!(i, Item::Func(f) if f.name == "m"))
    {
        out.push_str("\nm();\n");
    }

    out
}

fn emit_item(item: &Item, indent: usize, out: &mut String) {
    match item {
        Item::Import(i) => {
            if let Some(alias) = &i.alias {
                line(
                    indent,
                    &format!("const {} = require('./{}');", alias, i.module),
                    out,
                );
            } else {
                line(indent, &format!("require('./{}');", i.module), out);
            }
        }
        Item::Var(v) => emit_var(v, indent, out),
        Item::Func(f) => emit_func(f, indent, out),
        Item::Family(c) => emit_family(c, indent, out),
        Item::Stmt(s) => emit_stmt(s, indent, out),
    }
}

fn emit_var(v: &VarDecl, indent: usize, out: &mut String) {
    let kw = if v.is_fixed || v.temp == TempKind::Hot {
        "const"
    } else {
        "let"
    };
    line(
        indent,
        &format!("{} {} = {};", kw, v.name, emit_expr(&v.value)),
        out,
    );
}

fn emit_func(f: &FuncDecl, indent: usize, out: &mut String) {
    let args = f
        .params
        .iter()
        .map(|p| p.name.clone())
        .collect::<Vec<_>>()
        .join(", ");
    match &f.body {
        FuncBody::Block(stmts) => {
            line(indent, &format!("function {}({}) {{", f.name, args), out);
            for s in stmts {
                emit_stmt(s, indent + 1, out);
            }
            line(indent, "}", out);
        }
        FuncBody::Expr(e) => {
            line(
                indent,
                &format!(
                    "function {}({}) {{ return {}; }}",
                    f.name,
                    args,
                    emit_expr(e)
                ),
                out,
            );
        }
    }
}

fn emit_family(c: &FamilyDecl, indent: usize, out: &mut String) {
    let ext = c
        .extends
        .as_ref()
        .map(|e| format!(" extends {}", e))
        .unwrap_or_default();
    line(indent, &format!("class {}{} {{", c.name, ext), out);
    for m in &c.methods {
        let args = m
            .params
            .iter()
            .map(|p| p.name.clone())
            .collect::<Vec<_>>()
            .join(", ");
        let name = if m.name == "init" {
            "constructor"
        } else {
            &m.name
        };
        match &m.body {
            FuncBody::Expr(e) => {
                line(
                    indent + 1,
                    &format!("{}({}) {{ return {}; }}", name, args, emit_expr(e)),
                    out,
                );
            }
            FuncBody::Block(stmts) => {
                line(indent + 1, &format!("{}({}) {{", name, args), out);
                for s in stmts {
                    emit_stmt(s, indent + 2, out);
                }
                line(indent + 1, "}", out);
            }
        }
    }
    line(indent, "}", out);
}

fn emit_stmt(s: &Stmt, indent: usize, out: &mut String) {
    match s {
        Stmt::Var(v) => emit_var(v, indent, out),
        Stmt::Assign { target, value } => line(
            indent,
            &format!("{} = {};", emit_expr(target), emit_expr(value)),
            out,
        ),
        Stmt::Ret(e) => line(indent, &format!("return {};", emit_expr(e)), out),
        Stmt::Expr(e) => line(indent, &format!("{};", emit_expr(e)), out),
        Stmt::Repeat { times, body } => {
            line(
                indent,
                &format!("for (let __i = 0; __i < ({}); __i++) {{", emit_expr(times)),
                out,
            );
            for st in body {
                emit_stmt(st, indent + 1, out);
            }
            line(indent, "}", out);
        }
        Stmt::If {
            cond,
            then_block,
            elif_blocks,
            else_block,
        } => {
            line(indent, &format!("if ({}) {{", emit_expr(cond)), out);
            for st in then_block {
                emit_stmt(st, indent + 1, out);
            }
            line(indent, "}", out);
            for (ec, eb) in elif_blocks {
                line(indent, &format!("else if ({}) {{", emit_expr(ec)), out);
                for st in eb {
                    emit_stmt(st, indent + 1, out);
                }
                line(indent, "}", out);
            }
            if let Some(eb) = else_block {
                line(indent, "else {", out);
                for st in eb {
                    emit_stmt(st, indent + 1, out);
                }
                line(indent, "}", out);
            }
        }
    }
}

fn emit_expr(e: &Expr) -> String {
    match e {
        Expr::Number(n) => n.clone(),
        Expr::String(s) => s.clone(),
        Expr::Bool(b) => b.to_string(),
        Expr::Null => "null".into(),
        Expr::Ident(i) => match i.as_str() {
            "out" | "slout" | "in" | "inln" => format!("__mars.{}", i),
            "a" | "s" | "p" => format!("__mars.{}", i),
            "me" => "this".into(),
            _ => i.clone(),
        },
        Expr::Raw(r) => r.clone(),
        Expr::Member { object, field } => format!("{}.{}", emit_expr(object), field),
        Expr::Call { callee, args } => {
            format!(
                "{}({})",
                emit_expr(callee),
                args.iter().map(emit_expr).collect::<Vec<_>>().join(", ")
            )
        }
        Expr::Binary { left, op, right } => {
            format!("({} {} {})", emit_expr(left), op, emit_expr(right))
        }
    }
}

fn line(indent: usize, text: &str, out: &mut String) {
    out.push_str(&"    ".repeat(indent));
    out.push_str(text);
    out.push('\n');
}
